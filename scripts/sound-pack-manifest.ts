/**
 * Writes `src/app/domain/sound-pack.manifest.ts`: the files of the sound pack (#100) with their
 * size and SHA-256, read from a release of `@dsebastien/music-notation-sounds` on npm.
 *
 * The plugin downloads those files one by one and refuses a file whose size or hash differs, so
 * the list is part of the plugin's source: run this script when the pack moves to a new release,
 * and commit the result.
 *
 *     bun scripts/sound-pack-manifest.ts 0.1.1
 *
 * The package is not a dependency: only its bytes are hashed here, nothing of it runs.
 */
import { createHash } from 'node:crypto'
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const PACKAGE = '@dsebastien/music-notation-sounds'
const FOLDER = 'generaluser'
/** In the package for its maintainers (loudness measures); playing never reads it. */
const LEFT_OUT = new Set(['report.json'])
const TARGET = 'src/app/domain/sound-pack.manifest.ts'

export interface ManifestFile {
    name: string
    size: number
    sha256: string
}

/** The source text of the manifest module. */
export function manifestSource(version: string, files: ManifestFile[]): string {
    const rows = [...files]
        .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
        .map((file) => `    ['${file.name}', ${file.size}, '${file.sha256}']`)
    return [
        `// Generated by scripts/sound-pack-manifest.ts from ${PACKAGE}@${version}.`,
        '// Do not edit: run the script again when the pack moves to a new release.',
        '',
        '/** The release of the sounds package the pack is downloaded from. */',
        `export const SOUND_PACK_VERSION = '${version}'`,
        '',
        '/** Each file of the pack: its name, its size in bytes and its SHA-256 (hex). */',
        'export const SOUND_PACK_FILES: readonly (readonly [string, number, string])[] = [',
        rows.join(',\n'),
        ']',
        ''
    ].join('\n')
}

async function main(version: string): Promise<void> {
    const meta = (await (
        await fetch(`https://registry.npmjs.org/${PACKAGE.replace('/', '%2f')}/${version}`)
    ).json()) as { dist?: { tarball?: string; integrity?: string } }
    const tarball = meta.dist?.tarball
    const integrity = meta.dist?.integrity
    if (!tarball || !integrity?.startsWith('sha512-'))
        throw new Error(`${PACKAGE}@${version}: no tarball or sha512 on the registry`)
    const bytes = new Uint8Array(await (await fetch(tarball)).arrayBuffer())
    const sha512 = createHash('sha512').update(bytes).digest('base64')
    if (`sha512-${sha512}` !== integrity)
        throw new Error(`${PACKAGE}@${version}: the tarball does not match the registry's hash`)

    const dir = await mkdtemp(join(tmpdir(), 'sound-pack-'))
    try {
        const archive = join(dir, 'pack.tgz')
        await writeFile(archive, bytes)
        const tar = Bun.spawnSync(['tar', '-xzf', archive, '-C', dir])
        if (tar.exitCode !== 0) throw new Error(`tar failed: ${tar.stderr.toString()}`)
        const folder = join(dir, 'package', FOLDER)
        const files: ManifestFile[] = []
        for (const name of await readdir(folder)) {
            if (LEFT_OUT.has(name)) continue
            const data = await readFile(join(folder, name))
            files.push({
                name,
                size: data.byteLength,
                sha256: createHash('sha256').update(data).digest('hex')
            })
        }
        await writeFile(TARGET, manifestSource(version, files))
        const total = files.reduce((sum, file) => sum + file.size, 0)
        console.log(`${TARGET}: ${files.length} files, ${total} bytes, ${PACKAGE}@${version}`)
    } finally {
        await rm(dir, { recursive: true, force: true })
    }
}

if (import.meta.main) {
    const version = process.argv[2]
    if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
        console.error('Usage: bun scripts/sound-pack-manifest.ts <version, e.g. 0.1.1>')
        process.exit(1)
    }
    await main(version)
}
